import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { performance } from 'node:perf_hooks';
import { arrangeSong, loadSong } from '../engine/blocks';
import { createSong, moveKey, setEmotion } from '../engine/emotions';
import { applyRhythm } from '../engine/harmonic-rhythm';
import { audit } from '../engine/audit';
import { writeMidi } from '../engine/midi';
import { checkMidi } from '../tests/midi-check';
import type { Mode } from '../engine/types';

export function measureBlocks(): number {
  const out = 'renders/phase1b'; mkdirSync(out,{ recursive: true });
  const demos = [
    { file: 'hopeful-then-epic', feelings: ['hopeful','hopeful','epic','triumphant'], mode: 'major', meter: [4,4] },
    { file: 'mysterious-to-dread', feelings: ['mysterious','mysterious','dread','dread'], mode: 'phrygian', meter: [4,4] },
    { file: 'tender-waltz', feelings: ['tender','tender','hopeful','tender'], mode: 'major', meter: [3,4] },
    { file: 'key-lift-final-chorus', feelings: ['calm','hopeful','epic','triumphant'], mode: 'major', meter: [4,4] },
    { file: 'changing-chord-rhythms', feelings: ['calm','hopeful','determined','dreamy'], mode: 'minor', meter: [4,4] }
  ];
  const rows: string[] = [];
  for (const demo of demos) {
    const song = createSong(); song.key.mode = demo.mode as Mode; song.meter = demo.meter as [number,number];
    song.blocks.forEach((block,index) => setEmotion(song,block,demo.feelings[index]));
    if (demo.file === 'key-lift-final-chorus') {
      song.blocks[2].section = song.blocks[3].section = 'Chorus';
      moveKey(song,song.blocks[3],'lift'); song.blocks[2].bigEntrance = true;
    }
    if (demo.file === 'changing-chord-rhythms') song.blocks.forEach((block,index) => applyRhythm(song,block,(['breathe','unfold','lean','offbeat'] as const)[index]));
    const result = arrangeSong(song), metrics = audit(result), bytes = writeMidi(result);
    for (const metric of ['outsideFull','scaleConflicts','parallels','unresolved','runLandingErrors','invalidNotes','overlaps'] as const) assert.equal(metrics[metric],0,`${demo.file}: ${metric}`);
    checkMidi(bytes,result); assert.deepEqual(writeMidi(arrangeSong(loadSong(JSON.parse(JSON.stringify(song))))),bytes);
    const dry = arrangeSong({ ...song, controllers: false }); checkMidi(writeMidi(dry),dry);
    assert.deepEqual(result.parts.map(part => part.notes),dry.parts.map(part => part.notes));
    writeFileSync(`${out}/${demo.file}.mid`,bytes);
    writeFileSync(`${out}/${demo.file}.json`,JSON.stringify(song,null,2) + '\n');
    const lengths = [...new Set(result.score.chords.map(chord => Number((chord.duration / 960).toFixed(2))))].sort((first,second) => first - second);
    rows.push(`| ${demo.file} | ${metrics.notes} | ${metrics.outsideComfortPercent}% | ${lengths.join(', ')} | ${result.markers!.length} | 0 | yes |`);
  }
  const song = createSong(), timings: number[] = [];
  arrangeSong(song);
  for (let repeat = 0; repeat < 50; repeat++) { const start = performance.now(); arrangeSong(song); timings.push(performance.now() - start); }
  timings.sort((first,second) => first - second);
  writeFileSync('Measurements/Phase1b-results.md',`# Block builder — generated measurements\n\nGenerated by \`npm run measure\`. Every row passes the full note/core audit, independent MIDI read-back (CC on/off), project round-trip and byte determinism. Hard failures include range, scale, parallel-motion, resolution, run-landing, invalid-note and overlap errors.\n\n| Demo | Notes | Outside comfortable | Chord lengths (quarter-note beats) | Merged markers | Hard failures | Deterministic |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n\nWarm four-block arrangement generation: median ${timings[25].toFixed(2)} ms, p95 ${timings[47].toFixed(2)} ms over 50 runs on this Mac. This measures engine computation, not audible browser latency. WebAudio schedules its first warmed note 25 ms ahead of the audio clock; cold decoding/device latency is additional.\n\nThe 32,256-case emotion-bank matrix, 196 cross-key emotion pairs, 100 varied songs, isolation and UI checks are run by \`npm test\`, separately from these demo audits.\n`);
  console.log(`Block demos: ${demos.length}, all hard checks pass.`);
  return 0;
}
